#!/usr/bin/env python
"""Build the Quality catalog from the vendored validator rules and the guides.

`schema/validator/rules.json` is what gtfs-validator publishes about each notice
code: severity, summary, description, the files it reads and the fields of its
samples. `schema/guides/<code>.yaml` is ours: how the Quality assistant walks a
reader through one notice. This merges the two into
`src/gtfs_garage/data/guides.json`, which the viewer reads, so that a guide
never restates what the validator already publishes.

The checks are the point of having a build step at all. A guide is data written
against another project's field names, and those change between releases. Every
guide must be for a code the validator emits, and must pass `check_guide` in
`gtfs_garage.core.guides`, which the server also applies to a guide an analyst
saves. A guide that fails fails the build rather than shipping a step the viewer
would silently skip.

    scripts/build-guides.sh
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

import yaml

from gtfs_garage.core.guides import GuideError, check_guide, vocabulary

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "schema" / "validator" / "rules.json"
VERSION = ROOT / "schema" / "validator" / "VERSION"
GUIDES = ROOT / "schema" / "guides"
OUT = ROOT / "src" / "gtfs_garage" / "data" / "guides.json"

COMMENT = (
    "The Quality catalog: for every gtfs-validator notice code, what the "
    "validator says about it (from its rules.json) and, where one has been "
    "written, the guide the Quality assistant follows. Generated by "
    "scripts/build_guides.py from schema/validator/rules.json and "
    "schema/guides/*.yaml; do not edit by hand."
)


def plain(text: str) -> str:
    """The validator's description as plain text.

    A few descriptions carry an HTML table (the speed limits per route type);
    the viewer writes everything through `textContent`, so markup would show
    as markup. Rows become lines and cells are separated, which keeps such a
    table readable as text.
    """
    text = re.sub(r"</t[hd]>\s*", " | ", text, flags=re.I)
    text = re.sub(r"</tr>\s*", "\n", text, flags=re.I)
    text = re.sub(r"<[^>]+>", "", text)
    lines = [re.sub(r"\s*\|\s*$", "", re.sub(r"[ \t]+", " ", line).strip()) for line in text.splitlines()]
    # Paragraphs separated by a blank line keep it; a line wrapped mid-sentence
    # is joined back up.
    paragraphs, current = [], []
    for line in lines:
        if not line:
            if current:
                paragraphs.append(current)
                current = []
            continue
        current.append(line)
    if current:
        paragraphs.append(current)
    # A table's rows were separated by blank lines in the source; they are one
    # block here, one row per line.
    blocks: list[tuple[bool, list[str]]] = []
    for paragraph in paragraphs:
        tabular = any(" | " in line for line in paragraph)
        if tabular and blocks and blocks[-1][0]:
            blocks[-1][1].extend(paragraph)
        else:
            blocks.append((tabular, list(paragraph)))
    joined = ["\n".join(lines) if tabular else " ".join(lines) for tabular, lines in blocks]
    return html.unescape("\n\n".join(joined)).strip()


def notice_entry(rule: dict) -> dict:
    references = rule.get("references") or {}
    return {
        "severity": rule.get("severityLevel"),
        "summary": plain(rule.get("shortSummary") or ""),
        "description": plain(rule.get("description") or ""),
        "files": references.get("fileReferences") or [],
        "best_practices_files": references.get("bestPracticesFileReferences") or [],
        "sections": references.get("sectionReferences") or [],
        "urls": references.get("urlReferences") or [],
        "fields": {
            name: {"type": spec.get("type"), "description": plain(spec.get("description") or "")}
            for name, spec in sorted((rule.get("properties") or {}).items())
        },
        "deprecated": bool(rule.get("deprecated")),
    }


def build(rules_path: Path, guides_dir: Path) -> dict:
    rules = json.loads(rules_path.read_text(encoding="utf-8"))
    notices = {code: notice_entry(rule) for code, rule in sorted(rules.items())}

    for path in sorted(guides_dir.glob("*.yaml")):
        code = path.stem
        if code not in rules:
            raise GuideError(f"{path.name}: the validator has no notice called {code!r}")
        guide = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        notices[code]["guide"] = check_guide(code, guide, (rules[code].get("properties") or {}).keys())

    version = VERSION.read_text(encoding="utf-8").strip() if VERSION.exists() else None
    return {
        "comment": COMMENT,
        "validator": version,
        **vocabulary(),
        "notices": notices,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rules", type=Path, default=RULES)
    parser.add_argument("--guides", type=Path, default=GUIDES)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    try:
        catalog = build(args.rules, args.guides)
    except GuideError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    args.out.write_text(json.dumps(catalog, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    guided = sum(1 for notice in catalog["notices"].values() if "guide" in notice)
    print(
        f"{args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}: "
        f"{len(catalog['notices'])} notices, {guided} with a guide"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
